"""Command-line interface.

    agentconf-audit scan [PATH ...] [--auto] [--format text|json|md] [--output FILE]
                         [--fail-on high|medium|low|info|never] [--disable RULE,...]
    agentconf-audit rules [--markdown]
    agentconf-audit verify REPORT.json

Exit codes: 0 clean (below threshold), 1 findings at/above threshold, 2 usage or I/O error,
3 verification failed.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from . import __version__
from .loaders import default_locations, expand_paths, load_document
from .model import SEVERITIES, SEVERITY_RANK, Report
from .report import render_json, render_markdown, render_text, verify_report_dict
from .rules import all_rules, run_rules


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(prog="agentconf-audit",
                                description="Static security audit of AI coding-agent configuration files.")
    p.add_argument("--version", action="version", version=f"%(prog)s {__version__}")
    sub = p.add_subparsers(dest="cmd", required=True)

    s = sub.add_parser("scan", help="audit configuration files")
    s.add_argument("paths", nargs="*", help="files or directories; directories are searched for known config names")
    s.add_argument("--auto", action="store_true", help="also scan the well-known per-user locations on this machine")
    s.add_argument("--format", choices=("text", "json", "md"), default="text")
    s.add_argument("--output", "-o", help="write the report here instead of stdout")
    s.add_argument("--fail-on", choices=[x.lower() for x in SEVERITIES] + ["never"], default="high",
                   help="exit 1 when a finding of this severity or higher exists (default: high)")
    s.add_argument("--disable", default="", help="comma-separated rule ids to skip, e.g. GEN002,MCP005")
    s.add_argument("--no-timestamp", action="store_true", help="omit generated_at so output is byte-reproducible")
    s.set_defaults(func=cmd_scan)

    r = sub.add_parser("rules", help="list rules with rationale and stated blind spots")
    r.add_argument("--markdown", action="store_true")
    r.set_defaults(func=cmd_rules)

    v = sub.add_parser("verify", help="recompute report_sha256 of a JSON report")
    v.add_argument("report")
    v.set_defaults(func=cmd_verify)
    return p


def cmd_scan(args: argparse.Namespace) -> int:
    paths = list(expand_paths(args.paths))
    if args.auto:
        paths += default_locations()
    if not paths:
        print("error: no input files (give paths or use --auto)", file=sys.stderr)
        return 2
    disabled = {x.strip().upper() for x in args.disable.split(",") if x.strip()}
    report = Report()
    seen: set[str] = set()
    for path in paths:
        key = str(path.resolve()) if path.exists() else str(path)
        if key in seen:
            continue
        seen.add(key)
        if not path.is_file():
            print(f"error: not a file: {path}", file=sys.stderr)
            return 2
        try:
            doc = load_document(path)
        except OSError as e:
            print(f"error: cannot read {path}: {e}", file=sys.stderr)
            return 2
        report.inputs.append({"path": doc.path, "kind": doc.kind, "sha256": doc.sha256, "bytes": doc.size})
        report.findings.extend(f for f in run_rules(doc) if f.rule_id not in disabled)

    if args.format == "json":
        text = render_json(report, timestamp=not args.no_timestamp)
    elif args.format == "md":
        text = render_markdown(report, timestamp=not args.no_timestamp)
    else:
        text = render_text(report)
    if args.output:
        Path(args.output).write_text(text, encoding="utf-8")
    else:
        sys.stdout.write(text)

    if args.fail_on == "never":
        return 0
    threshold = SEVERITY_RANK[args.fail_on.upper()]
    return 1 if any(SEVERITY_RANK[f.severity] <= threshold for f in report.findings) else 0


def cmd_rules(args: argparse.Namespace) -> int:
    sys.stdout.write(rules_markdown() if args.markdown else rules_text())
    return 0


def rules_text() -> str:
    out = []
    for meta, _ in all_rules():
        out.append(f"{meta.id}  [{meta.severity}]  {meta.title}")
        out.append(f"    applies to: {', '.join(meta.applies_to)}")
        out.append(f"    why: {meta.rationale}")
        out.append(f"    not caught: {meta.not_caught}")
    return "\n".join(out) + "\n"


def rules_markdown() -> str:
    lines = ["# Rules", "",
             "Generated by `agentconf-audit rules --markdown`; `tests/test_docs.py` fails if this file drifts.", "",
             "Severity is the default for a full match; a rule may emit a lower severity for a weaker match "
             "(each rule's text says when).", ""]
    for meta, _ in all_rules():
        lines.append(f"## {meta.id} · {meta.title}")
        lines.append("")
        lines.append(f"- **Default severity:** {meta.severity}")
        lines.append(f"- **Applies to:** {', '.join(f'`{k}`' for k in meta.applies_to)}")
        lines.append(f"- **Why it matters:** {meta.rationale}")
        lines.append(f"- **Not caught:** {meta.not_caught}")
        lines.append("")
    return "\n".join(lines)


def cmd_verify(args: argparse.Namespace) -> int:
    try:
        d = json.loads(Path(args.report).read_text(encoding="utf-8"))
    except (OSError, ValueError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 2
    ok, expected, actual = verify_report_dict(d)
    if ok:
        print(f"OK  report_sha256 {actual} matches ({len(d.get('findings', []))} findings, "
              f"{len(d.get('inputs', []))} inputs)")
        return 0
    print(f"FAIL  report says {expected or '<missing>'}\n      body hashes to {actual}")
    return 3


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    return args.func(args)


if __name__ == "__main__":  # pragma: no cover
    sys.exit(main())
